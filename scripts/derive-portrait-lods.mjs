/**
 * One-time, dependency-free LOD generator from the existing neutral ASCII map.
 * No photographs, segmentation model or Python are needed in the web build.
 * Run: node scripts/derive-portrait-lods.mjs
 *
 * The fine map has already been quantized. Averaging its approximate tonal
 * values sacrifices some detail, but guarantees identical crop and alignment.
 */
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync("src/components/hero-portrait-rows.ts", "utf8");
const match = source.match(/export const portraitRows = (\[[\s\S]*?\]);/);
if (!match) throw new Error("Could not find neutral portrait rows");

const fine = JSON.parse(match[1]);
const glyphs = " .:-=+*#%@";

function downsample(factor) {
  return Array.from({ length: fine.length / factor }, (_, row) =>
    Array.from({ length: fine[0].length / factor }, (_, col) => {
      let sum = 0;
      let peak = 0;
      let occupied = 0;
      for (let y = 0; y < factor; y++) {
        for (let x = 0; x < factor; x++) {
          const value = glyphs.indexOf(fine[row * factor + y][col * factor + x]);
          if (value < 0) throw new Error("Unexpected glyph in source map");
          sum += value;
          peak = Math.max(peak, value);
          if (value) occupied++;
        }
      }
      // Keep thin curls and facial marks, without turning the negative space
      // between hair and cheek into a square block.
      if (occupied < Math.ceil(factor * factor * 0.18)) return " ";
      const tone = sum / (factor * factor);
      const boosted = tone * 0.84 + peak * 0.16;
      return glyphs[Math.min(10, Math.max(1, Math.round(boosted)))];
    }).join(""),
  );
}

const coarse = downsample(4);
const medium = downsample(2);
writeFileSync(
  "src/components/hero-portrait-lods.ts",
  "// Generated by scripts/derive-portrait-lods.mjs — do not hand-edit.\n" +
    "// Derived from the existing neutral 160 × 140 map, without new photo processing.\n" +
    `export const coarsePortraitRows = ${JSON.stringify(coarse, null, 2)};\n` +
    `export const mediumPortraitRows = ${JSON.stringify(medium, null, 2)};\n`,
);
console.log(`Generated ${coarse[0].length} × ${coarse.length} and ${medium[0].length} × ${medium.length} maps.`);
