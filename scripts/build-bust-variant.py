"""Build only experimental bust assets from the approved phase-1 geometry.

Run: python scripts/build-bust-variant.py && node scripts/derive-bust-lods.mjs
The source PNG and approved head-only assets are read-only.
"""

import importlib.util
import json
import sys
from pathlib import Path
from xml.sax.saxutils import escape

from PIL import Image, ImageOps


ROOT = Path(__file__).resolve().parent.parent
sys.dont_write_bytecode = True
spec = importlib.util.spec_from_file_location("bust_preview", ROOT / "scripts/preview-bust-aspect.py")
assert spec and spec.loader
preview = importlib.util.module_from_spec(spec)
spec.loader.exec_module(preview)

fixture = ROOT / "scripts/fixtures/bust-aspect-approved-rows.json"
rows = json.loads(fixture.read_text())
if preview.SOURCE.exists():
    source = ImageOps.exif_transpose(Image.open(preview.SOURCE)).convert("RGBA")
    if source.size != (3264, 4928):
        raise ValueError("Unexpected source image size")
    box, _, _ = preview.grid_geometry()
    if box != (-24, 513, 3288, 5017):
        raise ValueError(f"Unexpected approved crop: {box}")
    generated, _ = preview.glyph_map(source.crop(box))
    if generated != rows:
        raise ValueError("PNG conversion differs from the approved phase-1 rows")
else:
    print(f"Source PNG unavailable; using the exact phase-1 fixture: {fixture}")
assert len(rows) == 180 and all(len(row) == 216 for row in rows)

(ROOT / "src/components/hero-portrait-rows-variant-bust-test.ts").write_text(
    "// Generated by scripts/build-bust-variant.py from the approved proportional GIMP crop.\n"
    "// 216 × 180; 4.375 × 7.14 cells. Do not edit the head-only maps.\n"
    f"export const portraitRows = {json.dumps(rows, indent=2)};\n"
)

# Canvas stretches the measured monospace glyph to exactly one physical cell;
# lengthAdjust gives the SVG precisely the same horizontal glyph spacing.
svg = [
    '<svg xmlns="http://www.w3.org/2000/svg" width="945" height="1285.2" '
    'viewBox="0 0 945 1285.2" role="img">',
    '<g fill="#dcdcde" fill-opacity=".78" font-family="monospace" '
    'font-size="7.14" font-weight="500" xml:space="preserve">',
]
for y, row in enumerate(rows):
    trimmed = row.rstrip()
    if trimmed:
        svg.append(
            f'<text x="0" y="{(y + 1) * 7.14:g}" '
            f'textLength="{len(trimmed) * 4.375:g}" lengthAdjust="spacingAndGlyphs">'
            f"{escape(trimmed)}</text>"
        )
(ROOT / "public/portraits/variant-bust-test-ascii.svg").write_text(
    "\n".join(svg + ["</g>", "</svg>", ""])
)
print("Built proportional 216 × 180 bust fine map and SVG")
