"""Convert the hand-edited transparent neutral portrait to ASCII for the bust test.

Run with the external portrait venv. The PNG and approved maps are read-only.
"""

import json
import math
import subprocess
from pathlib import Path
from xml.sax.saxutils import escape

import numpy as np
from PIL import Image, ImageDraw, ImageFilter, ImageFont, ImageOps


ROOT = Path(__file__).resolve().parent.parent
SOURCE = Path.home() / "Pictures/fotosperfil/Câmera/selecionadas/editadas/_DSC2311.png"
GLYPHS = " .:-=+*#%@"
EYES = ((1115, 2265), (1900, 2265))  # EXIF-upright pixel coordinates


def make_ascii():
    # A single continuous conversion of the *entire* neutral photo; the
    # approved portrait supplies only the eye-centered crop geometry.
    image = ImageOps.exif_transpose(Image.open(SOURCE)).convert("RGBA")
    left, right = EYES
    distance = math.dist(left, right)
    width = distance / 0.32
    height = width / 0.7
    center_x = (left[0] + right[0]) / 2
    center_y = (left[1] + right[1]) / 2
    rows_count = 180
    crop = (round(center_x - width / 2), round(center_y - height / 2),
            round(center_x + width / 2),
            round(center_y + height / 2 + (rows_count - 140) * height / 140))
    image = image.crop(crop).resize((640, rows_count * 4), Image.Resampling.LANCZOS)
    rgb = image.convert("RGB")
    gray = ImageOps.grayscale(rgb)
    pixels = np.asarray(gray, dtype=np.float32) / 255
    pixels = np.power(pixels, 0.83)
    local = np.asarray(Image.fromarray(np.uint8(pixels * 255)).filter(
        ImageFilter.GaussianBlur(6)), dtype=np.float32) / 255
    gray = Image.fromarray(np.uint8(np.clip(pixels + (pixels - local) * 0.85, 0, 1) * 255), "L")
    gray = np.asarray(gray.resize((160, rows_count), Image.Resampling.BOX), dtype=np.float32) / 255
    alpha = np.asarray(image.getchannel("A").resize((160, rows_count), Image.Resampling.BOX),
                       dtype=np.float32) / 255
    rows = []
    for y in range(rows_count):
        line = []
        for x in range(160):
            if alpha[y, x] < 0.28 or y >= 179:
                line.append(" ")
                continue
            strength = max(0, (1 - gray[y, x] - 0.10) / 0.90) * min(1, alpha[y, x] * 1.2)
            # Same gentle hair reduction as the approved photo converter.
            if y < 140 * 0.39:
                strength *= 0.78
            # Stop the original photo boundary from becoming a hard shirt bar.
            # This is a bottom-opacity finish, not a silhouette/head crop.
            fade = min(1, max(0, (179 - y) / 17))
            if fade < 1 and (
                math.sin(x * 127.1 + y * 311.7) * 43758.5453 % 1
            ) > fade:
                line.append(" ")
                continue
            strength *= fade
            index = min(9, round(strength * 9))
            line.append(GLYPHS[index])
        rows.append("".join(line))
    assert len(rows) == rows_count and all(len(row) == 160 for row in rows)
    target = ROOT / "src/components/hero-portrait-rows-variant-bust-test.ts"
    target.write_text(
        "// Generated by scripts/prepare-bust-variant.py from editadas/_DSC2311.png (GIMP).\n"
        "// Entire head, neck and bust derived from the new photo; 160 × 180, eyes at row 70.\n"
        f"export const portraitRows = {json.dumps(rows, indent=2)};\n"
    )
    svg = ROOT / "public/portraits/variant-bust-test-ascii.svg"
    lines = [
        '<svg xmlns="http://www.w3.org/2000/svg" width="700" height="1285.2" viewBox="0 0 700 1285.2" role="img">',
        '<g fill="#dcdcde" fill-opacity=".78" font-family="monospace" font-size="7.14" font-weight="500" xml:space="preserve">',
    ]
    for y, row in enumerate(rows):
        if row.strip():
            lines.append(f'<text x="0" y="{(y + 1) * 7.14:g}">{escape(row.rstrip())}</text>')
    svg.write_text("\n".join(lines + ["</g>", "</svg>", ""]))
    print(f"Saved {target} and {svg}", flush=True)
    preview(image, rows)


def preview(photo, rows):
    """Full un-clipped portrait on a neutral background, before hero integration."""
    output = Path("/tmp/opencode")
    output.mkdir(parents=True, exist_ok=True)
    char_width, char_height = 8, 13
    art = Image.new("RGB", (160 * char_width, len(rows) * char_height), "#1c1c1e")
    font_path = subprocess.check_output(
        ["fc-match", "-f", "%{file}", "monospace"], text=True).strip()
    font = ImageFont.truetype(font_path, 15)
    glyphs = Image.new("RGB", (160 * 10, len(rows) * 17), "#1c1c1e")
    draw = ImageDraw.Draw(glyphs)
    for y, row in enumerate(rows):
        draw.text((0, y * 17 - 2), row, font=font, fill="#dcdcde")
    art.paste(glyphs.resize(art.size, Image.Resampling.LANCZOS))
    art.save(output / "bust-gimp-ascii-full-preview.png")
    photo_layer = Image.new("RGBA", art.size, "#1c1c1e")
    photo_layer.alpha_composite(photo.resize(art.size, Image.Resampling.LANCZOS))
    comparison = Image.new("RGB", (art.width * 2 + 80, art.height + 75), "#1c1c1e")
    comparison.paste(photo_layer.convert("RGB"), (20, 55))
    comparison.paste(art, (art.width + 60, 55))
    label = ImageDraw.Draw(comparison)
    label.text((20, 18), "PNG GIMP / TRANSPARENCIA ORIGINAL", font=font, fill="#dcdcde")
    label.text((art.width + 60, 18), "ASCII INTEGRAL / SEM CLIPPING", font=font, fill="#dcdcde")
    comparison.save(output / "bust-gimp-photo-ascii-comparison.png")


if __name__ == "__main__":
    make_ascii()
