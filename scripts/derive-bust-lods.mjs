/** Derive the four additional bust LOD pairs; verify but never rewrite neutral. */
import { readFileSync, writeFileSync } from "node:fs";

const glyphs = " .:-=+*#%@";
function readFine(path) {
  const match = readFileSync(path, "utf8").match(/export const portraitRows = (\[[\s\S]*?\]);/);
  if (!match) throw new Error(`Bust map not found: ${path}`);
  const fine = JSON.parse(match[1]);
  if (fine.length !== 180 || fine.some((row) => row.length !== 216))
    throw new Error(`Expected 216 × 180: ${path}`);
  return fine;
}
function downsample(fine, factor) {
  return Array.from({ length: fine.length / factor }, (_, row) =>
    Array.from({ length: fine[0].length / factor }, (_, col) => {
      let sum = 0, peak = 0, occupied = 0;
      for (let y = 0; y < factor; y++) for (let x = 0; x < factor; x++) {
        const value = glyphs.indexOf(fine[row * factor + y][col * factor + x]);
        if (value < 0) throw new Error("Unexpected glyph");
        sum += value;
        peak = Math.max(peak, value);
        if (value) occupied++;
      }
      if (occupied < Math.ceil(factor * factor * 0.18)) return " ";
      return glyphs[Math.min(9, Math.max(1, Math.round(sum / (factor * factor) * 0.84 + peak * 0.16)))];
    }).join(""),
  );
}
function output(fine) {
  return `// Generated by scripts/derive-bust-lods.mjs; approved LODs untouched.\n` +
    `export const coarsePortraitRows = ${JSON.stringify(downsample(fine, 4), null, 2)};\n` +
    `export const mediumPortraitRows = ${JSON.stringify(downsample(fine, 2), null, 2)};\n`;
}
const prefix = "src/components/hero-portrait-";
const neutral = output(readFine(`${prefix}rows-variant-bust-test.ts`));
if (readFileSync(`${prefix}lods-variant-bust-test.ts`, "utf8") !== neutral)
  throw new Error("Neutral LODs differ from approved generation; refusing to write");
for (const expression of ["thinking", "angry", "disgust", "smile"]) {
  const fine = readFine(`${prefix}rows-variant-bust-${expression}.ts`);
  writeFileSync(`${prefix}lods-variant-bust-${expression}.ts`, output(fine));
}
