/**
 * Derive additional expressions from their existing aligned 160 × 140 maps.
 * Never overwrites the neutral C7 LOD file or any fine map.
 * Run: node scripts/derive-expression-lods.mjs [expression ...]
 * Existing generated maps are never overwritten.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const glyphs = " .:-=+*#%@";
const sources = {
  thinking: "dsc2350",
  angry: "dsc2347",
  disgust: "dsc2352",
  smile: "dsc2341",
};

function downsample(fine, factor) {
  return Array.from({ length: fine.length / factor }, (_, row) =>
    Array.from({ length: fine[0].length / factor }, (_, col) => {
      let sum = 0;
      let peak = 0;
      let occupied = 0;
      for (let y = 0; y < factor; y++) {
        for (let x = 0; x < factor; x++) {
          const value = glyphs.indexOf(fine[row * factor + y][col * factor + x]);
          if (value < 0) throw new Error("Unexpected glyph in source map");
          sum += value;
          peak = Math.max(peak, value);
          if (value) occupied++;
        }
      }
      if (occupied < Math.ceil(factor * factor * 0.18)) return " ";
      const tone = sum / (factor * factor);
      return glyphs[Math.min(10, Math.max(1, Math.round(tone * 0.84 + peak * 0.16)))];
    }).join(""),
  );
}

const requested = process.argv.slice(2);
for (const expression of requested) {
  if (!(expression in sources)) throw new Error(`Unknown expression: ${expression}`);
}
for (const [expression, source] of Object.entries(sources)) {
  if (requested.length && !requested.includes(expression)) continue;
  const output = `src/components/hero-portrait-lods-${expression}.ts`;
  if (existsSync(output)) {
    console.log(`Keeping existing ${output}`);
    continue;
  }
  const text = readFileSync(`src/components/hero-portrait-rows-${source}.ts`, "utf8");
  const match = text.match(/export const portraitRows = (\[[\s\S]*?\]);/);
  if (!match) throw new Error(`Missing fine map: ${source}`);
  const fine = JSON.parse(match[1]);
  if (fine.length !== 140 || fine.some((line) => line.length !== 160))
    throw new Error(`Unaligned map: ${source}`);
  const coarse = downsample(fine, 4);
  const medium = downsample(fine, 2);
  writeFileSync(output,
    `// Generated by scripts/derive-expression-lods.mjs from ${source}; do not hand-edit.\n` +
    `export const coarsePortraitRows = ${JSON.stringify(coarse, null, 2)};\n` +
    `export const mediumPortraitRows = ${JSON.stringify(medium, null, 2)};\n`);
}
